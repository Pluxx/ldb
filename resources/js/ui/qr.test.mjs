const toRows = (qr) => qr.modules.map((r) => r.map((d) => (d ? '1' : '0')).join(''));

/** Expected 15-bit format info, computed by brute-force search over the BCH(15,5) code. */
function expectedFormat(ecl, mask) {
  const data = ({ L: 1, M: 0, Q: 3, H: 2 })[ecl] << 3 | mask;
  for (let rem = 0; rem < 1024; rem++) {
    let v = (data << 10) | rem;
    // valid codeword iff divisible by generator 0x537
    let r = v;
    for (let i = 14; i >= 10; i--) if ((r >> i) & 1) r ^= 0x537 << (i - 10);
    if (r === 0) return v ^ 0x5412;
  }
  throw new Error('unreachable');
}

function checkMatches(name, opts) {
  const ref = REF[name];
  const qr = encodeQR(ref.text, opts);
  assert.equal(qr.version, ref.version, `${name} version`);
  assert.equal(qr.mask, ref.mask, `${name} mask`);
  assert.equal(qr.ecl, ref.ecl);
  assert.deepEqual(toRows(qr), ref.rows, `${name} matrix`);
}

test('short string, forced mask matches reference', () => checkMatches('short_forced', { mask: 3 }));
test('short string, automatic mask matches reference', () => checkMatches('short_auto', {}));
test('otpauth URI (version >= 7) with auto mask matches reference', () => {
  assert.ok(REF.otp.version >= 7);
  checkMatches('otp', {});
});
test('otpauth URI with forced mask matches reference', () => checkMatches('otp_m5', { mask: 5 }));
test('non-ASCII UTF-8 matches reference', () => checkMatches('utf8', {}));
test('ECC level Q matches reference', () => checkMatches('hi_q', { ecl: 'Q' }));

test('structural sanity of all reference cases', () => {
  for (const [name, ref] of Object.entries(REF)) {
    const qr = encodeQR(ref.text, { ecl: ref.ecl });
    const { modules: m, size, version } = qr;
    assert.equal(size, 17 + 4 * version);
    assert.equal(m.length, size);
    // finder patterns with separators
    for (const [ox, oy] of [[0, 0], [size - 7, 0], [0, size - 7]]) {
      for (let y = 0; y < 7; y++) {
        for (let x = 0; x < 7; x++) {
          const ring = Math.max(Math.abs(x - 3), Math.abs(y - 3));
          assert.equal(m[oy + y][ox + x], ring !== 2, `${name} finder`);
        }
      }
    }
    for (let i = 0; i < 8; i++) {
      assert.equal(m[7][i], false);
      assert.equal(m[i][7], false);
      assert.equal(m[7][size - 1 - i], false);
      assert.equal(m[i][size - 8], false);
      assert.equal(m[size - 8][i], false);
      assert.equal(m[size - 1 - i][7], false);
    }
    // timing patterns
    for (let i = 8; i < size - 8; i++) {
      assert.equal(m[6][i], i % 2 === 0);
      assert.equal(m[i][6], i % 2 === 0);
    }
    // dark module
    assert.equal(m[4 * version + 9][8], true);
    // format info, both copies (bit i, LSB first)
    const f = expectedFormat(ref.ecl, qr.mask);
    const bit = (i) => ((f >> i) & 1) === 1;
    const c1 = [[0, 8], [1, 8], [2, 8], [3, 8], [4, 8], [5, 8], [7, 8], [8, 8], [8, 7], [8, 5], [8, 4], [8, 3], [8, 2], [8, 1], [8, 0]]; // [y, x]
    c1.forEach(([y, x], i) => assert.equal(m[y][x], bit(i), `${name} format copy 1 bit ${i}`));
    for (let i = 0; i < 8; i++) assert.equal(m[8][size - 1 - i], bit(i), `${name} format copy 2 bit ${i}`);
    for (let i = 8; i < 15; i++) assert.equal(m[size - 15 + i][8], bit(i), `${name} format copy 2 bit ${i}`);
    // version info
    if (version >= 7) {
      let rem = version;
      for (let i = 0; i < 12; i++) rem = (rem << 1) ^ ((rem >> 11) * 0x1f25);
      const v = (version << 12) | rem;
      for (let i = 0; i < 18; i++) {
        const want = ((v >> i) & 1) === 1;
        assert.equal(m[Math.floor(i / 3)][size - 11 + (i % 3)], want, `${name} version bit ${i}`);
        assert.equal(m[size - 11 + (i % 3)][Math.floor(i / 3)], want);
      }
    }
  }
});

test('smallest version is chosen and capacity limits hold', () => {
  assert.equal(encodeQR('a'.repeat(14)).version, 1); // v1-M holds 14 bytes
  assert.equal(encodeQR('a'.repeat(15)).version, 2);
  assert.equal(encodeQR('a'.repeat(213)).version, 10); // v10-M holds 213 bytes
  assert.throws(() => encodeQR('a'.repeat(214)), /qr: data too long/);
  assert.throws(() => encodeQR('a'.repeat(272), { ecl: 'L' }), /qr: data too long/);
  assert.equal(encodeQR('a'.repeat(271), { ecl: 'L' }).version, 10);
});

test('qrPath emits only M/h/v/z commands and numbers', () => {
  const qr = encodeQR('HELLO world');
  const d = qrPath(qr);
  assert.ok(d.length > 0);
  assert.match(d, /^(?:M\d+ \d+h\d+v1h-\d+z)+$/);
  // total drawn width equals the number of dark modules
  const area = [...d.matchAll(/h(\d+)v1/g)].reduce((s, x) => s + Number(x[1]), 0);
  assert.equal(area, qr.modules.flat().filter(Boolean).length);
  assert.ok(d.startsWith('M'));
});
